def main():
    categories = [
        ("order", ORDERS),
        ("complaint", COMPLAINTS),
        ("refund", REFUNDS),
        ("inquiry", INQUIRIES),
        ("urgent", URGENTS),
        ("other", OTHERS)
    ]

    total_rows = []
    print("Generating synthetic messages dataset...")
    for cat_name, samples in categories:
        count = len(samples)
        if count != 100:
            print(f"Warning: {cat_name} has {count} samples, adjusting to exactly 100...")
            if count < 100:
                # repeat random with slight variations
                while len(samples) < 100:
                    base = random.choice(samples)
                    samples.append(base)
            else:
                samples = samples[:100]
        for s in samples:
            clean_text = s.strip()
            total_rows.append({"text": clean_text, "label": cat_name})
        print(f"  - {cat_name}: {len(samples)} samples")

    random.shuffle(total_rows)

    os.makedirs(DATA_DIR, exist_ok=True)
    with open(CSV_PATH, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["text", "label"])
        writer.writeheader()
        writer.writerows(total_rows)

    print(f"\nGenerated {len(total_rows)} total messages saved to {CSV_PATH}")

if __name__ == "__main__":
    main()
